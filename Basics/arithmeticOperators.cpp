#include <iostream>
using namespace std;

int main()
{
    int a = 10;
    int b = 5;

    cout << "Sum = " << (a + b) << endl;
    cout << "Difference = " << (a - b) << endl;
    cout << "Product = " << (a * b) << endl;
    cout << "Division = " << (a / b) << endl;
    cout << "Modulo = " << (a % b) << endl;

    return 0;
}
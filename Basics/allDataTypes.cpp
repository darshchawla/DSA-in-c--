#include<iostream> 
using namespace std;

int main()
{
    // int
    int x = 7;
    cout << x << endl;

    // long
    long y = 15;
    cout << y << endl;

    // long long
    long long z = 150000000;
    cout << z << endl;

    // float, double
    float a = 7.5;
    float b = 7;
    double c = 9;
    cout << a << ", " << b << ", " << c << endl;

    // char
    char ch = 'a';
    cout << ch << endl;

    // string
    string str;
    cout << "Enter a string : ";
    cin >> str;
    cout << str << endl;
}